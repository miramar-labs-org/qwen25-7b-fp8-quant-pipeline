#!/usr/bin/env python3
"""
Assemble pipeline.py from tagged notebook cells.

Usage:
  python3 scripts/build_pipeline.py
  python3 scripts/build_pipeline.py --notebook path/to/notebook.ipynb

Cells tagged `kfp_step` become component functions.
The cell tagged `kfp_pipeline` becomes the pipeline() function.

The `quantize` step's `# <<< HF_PTQ_VENDOR_INJECT >>>` marker is replaced with
three repr()-escaped string constants holding the vendored NVIDIA Model-Optimizer
PTQ scripts (`vendor/hf_ptq.py`, `vendor/example_utils.py`,
`vendor/cast_mxfp4_to_nvfp4.py`) — repr() is used (not a triple-quoted literal)
because the vendored files contain triple-quoted docstrings that would break
naive string embedding.
"""
import argparse
import json
import pathlib
import re
import textwrap


def build_pipeline(
    notebook_path="notebook.ipynb",
    hf_ptq_path="vendor/hf_ptq.py",
    example_utils_path="vendor/example_utils.py",
    cast_mxfp4_to_nvfp4_path="vendor/cast_mxfp4_to_nvfp4.py",
):
    base_dir = pathlib.Path(notebook_path).parent
    nb = json.loads(pathlib.Path(notebook_path).read_text())
    hf_ptq_src = (base_dir / hf_ptq_path).read_text()
    example_utils_src = (base_dir / example_utils_path).read_text()
    cast_mxfp4_to_nvfp4_src = (base_dir / cast_mxfp4_to_nvfp4_path).read_text()

    step_srcs, pipeline_src = [], None
    for cell in nb["cells"]:
        if cell["cell_type"] != "code":
            continue
        tags = cell.get("metadata", {}).get("tags", [])
        src = "".join(cell["source"])
        if "kfp_step" in tags:
            if "# <<< HF_PTQ_VENDOR_INJECT >>>" in src:
                vendor_consts = (
                    f"_HF_PTQ_SRC = {hf_ptq_src!r}\n"
                    f"_EXAMPLE_UTILS_SRC = {example_utils_src!r}\n"
                    f"_CAST_MXFP4_TO_NVFP4_SRC = {cast_mxfp4_to_nvfp4_src!r}"
                )
                src = src.replace(
                    "    # <<< HF_PTQ_VENDOR_INJECT >>>",
                    textwrap.indent(vendor_consts, "    "),
                )
            step_srcs.append(src)
        elif "kfp_pipeline" in tags:
            pipeline_src = src

    if not step_srcs:
        raise RuntimeError("No cells tagged 'kfp_step' found in notebook.")
    if pipeline_src is None:
        raise RuntimeError("No cell tagged 'kfp_pipeline' found in notebook.")

    names = [
        m.group(1)
        for src in step_srcs
        for m in [re.search(r"^def (\w+)\(", src, re.MULTILINE)]
        if m
    ]

    out  = "# Generated by notebook.ipynb — do not edit manually.\n"
    out += "# Re-run scripts/build_pipeline.py (or the Build cell) to regenerate.\n\n"
    out += "from kfp import dsl\n"
    out += "from kfp import kubernetes\n"
    out += "from kfp.dsl import Input, Output, Dataset, Model, Metrics, Artifact\n\n\n"
    out += "\n\n\n".join(step_srcs)
    out += "\n\n\n"
    out += pipeline_src
    out += "\n"
    pathlib.Path("pipeline.py").write_text(out)
    print(f"Wrote pipeline.py — {len(names)} component(s): {', '.join(names)}")


if __name__ == "__main__":
    parser = argparse.ArgumentParser()
    parser.add_argument("--notebook", default="notebook.ipynb")
    args = parser.parse_args()
    build_pipeline(args.notebook)
